def hdr(ws, row, cols, widths=None):
    for i, h in enumerate(cols, 1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = Font(name=F, bold=True, color="FFFFFF", size=9)
        c.fill = HDR
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        c.border = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
    ws.row_dimensions[row].height = 32
    for i, w in enumerate(widths or [], 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def title(ws, t, sub):
    ws["A1"] = t
    ws["A1"].font = Font(name=F, bold=True, size=14, color=INK)
    ws["A2"] = sub
    ws["A2"].font = Font(name=F, italic=True, size=9, color="5B6B7F")


def inp(c, v, fmt=None):
    c.value = v
    c.fill = YELLOW
    c.font = Font(name=F, size=9, color="0000FF")
    if fmt:
        c.number_format = fmt


def fx(c, f, fmt=None, bold=False, color="000000"):
    c.value = f
    c.font = Font(name=F, size=9, bold=bold, color=color)
    if fmt:
        c.number_format = fmt


def gstin_check_formula(cell):
    idx = "{" + ",".join(str(i) for i in range(1, 15)) + "}"
    fac = "{" + ",".join("1" if i % 2 else "2" for i in range(1, 15)) + "}"
    code = f'(FIND(MID(UPPER({cell}),{idx},1),"{CS}")-1)*{fac}'
    s = f"SUMPRODUCT(INT({code}/36)+MOD({code},36))"
    return (f'=IF({cell}="","Unregistered",IF(LEN({cell})<>15,"Invalid length",IFERROR(IF(MID("{CS}",MOD(36-MOD({s},36),36)+1,1)'
            f'=RIGHT(UPPER({cell}),1),"Valid","Check digit error"),"Invalid characters")))')


